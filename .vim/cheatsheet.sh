#!/bin/sh
# Generates .vim/CHEATSHEET.md: vim's default buffer/window/cursor/editing keys, plus the
# custom overrides actually defined in .vimrc (and any .vim/core, .vim/stacks modules that
# exist yet), read from the files themselves rather than hand-copied -- so the custom-map
# table can't silently drift from what .vimrc really binds.
#
# Run it by hand after changing a mapping: .vim/cheatsheet.sh
#
# POSIX sh, no deps beyond grep/sed/awk -- same rules as scripts/lib.sh callers, even
# though this script lives outside the install.d contract (it writes .vim/CHEATSHEET.md,
# a repo file, not $TARGET or $HOME).

set -eu

SCRIPT_DIR=$(cd "$(dirname "$0")" && pwd)
REPO=$(cd "$SCRIPT_DIR/.." && pwd)
VIMRC="$REPO/.vimrc"
OUT="$REPO/.vim/CHEATSHEET.md"

# Every vimscript file that can define custom mappings, in load order. Globs that match
# nothing (.vim/core, .vim/stacks not built yet) are dropped rather than passed through
# literally, which is what the -f test is for.
MAP_SOURCES="$VIMRC"
for f in "$REPO"/.vim/core/*.vim "$REPO"/.vim/stacks/*/*.vim; do
  [ -f "$f" ] && MAP_SOURCES="$MAP_SOURCES $f"
done

# --- extract statically-written nnoremap/inoremap/vnoremap lines -----------------------
# Catches `nnoremap <C-a> <Home>`-style lines directly. Loop/execute-built mappings (the
# Alt-hjkl focus/resize table in .vimrc) don't match this shape -- vimscript string
# concatenation isn't worth parsing here -- so those are listed by hand in the "generated
# at runtime" section below, next to a note pointing at the loop that builds them.
extract_static() {
  grep -hEn '^(nnoremap|inoremap|vnoremap)(\s+<silent>)?\s+\S+\s+\S' $MAP_SOURCES 2>/dev/null \
    | grep -Ev "^\S*:\s*(nnoremap|inoremap|vnoremap)\s+<silent>" \
    || true
}

# Build one row per distinct LHS key, showing which of n/i/v it's bound in and the RHS
# (mode column collapses n+i+v into one row when the RHS is identical across all three,
# which is how every static mapping in .vimrc is actually written).
# Plain field-splitting rather than gawk's match(str, re, arr) -- that's a gawk extension,
# not POSIX, and macOS ships BSD awk with no gawk in its base install. One line in, one
# mode/key/rhs triple out.
static_table() {
  extract_static | sed -E 's/^[0-9]+:[[:space:]]*//' | awk '
    {
      mode = substr($1, 1, 1)
      i = 2
      if ($2 == "<silent>") i = 3
      key = $i
      rhs = ""
      for (j = i + 1; j <= NF; j++) rhs = rhs (j > i + 1 ? " " : "") $j
      order_key = key "\x1c" rhs
      if (!(order_key in seen)) { order[++n] = order_key; seen[order_key] = 1 }
      modes[order_key] = modes[order_key] mode
    }
    END {
      for (i = 1; i <= n; i++) {
        split(order[i], parts, "\x1c")
        key = parts[1]; rhs = parts[2]
        m = modes[order[i]]
        label = (index(m, "n") && index(m, "i") && index(m, "v")) ? "N/I/V" : \
                (index(m, "n") && index(m, "v")) ? "N/V" : \
                (index(m, "n") && index(m, "i")) ? "N/I" : \
                (index(m, "n")) ? "N" : (index(m, "i")) ? "I" : "V"
        printf "| `%s` | %s | `%s` |\n", key, label, rhs
      }
    }
  '
}

STATIC_ROWS=$(static_table)

cat > "$OUT" <<EOF
# vim cheatsheet

Generated by \`.vim/cheatsheet.sh\` from$([ "$MAP_SOURCES" != "$VIMRC" ] && echo " .vimrc and .vim/core, .vim/stacks" || echo " .vimrc"). Custom
mappings below are read out of the config, not hand-copied — re-run the script after
changing a mapping. Defaults tables are vim's own, unaffected by this repo's config.

Notation: \`<C-x>\` = Ctrl-x, \`<M-x>\` = Alt-x (Option on macOS), \`<S-x>\` = Shift-x.
\`N\`/\`I\`/\`V\` = Normal / Insert / Visual mode. See \`scripts/keyboard/CHEATSHEET.md\` for why
Alt is the in-terminal modifier and how it reaches vim at all.

