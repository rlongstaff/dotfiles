| Key | Mode | Action |
| --- | ---- | ------ |
$STATIC_ROWS

### Generated at runtime (loop-built, not a literal \`nnoremap\` line)

.vimrc builds these from a table rather than writing one \`nnoremap\` per key, so they don't
show up in the grep above. Two tables: pane/split **focus** and **resize**, both shared
with tmux — at the edge of vim's splits the key hands off to \`tmux select-pane\` /
\`tmux resize-pane\` instead of doing nothing. See \`s:VimIdeFocus\`/\`s:VimIdeResize\` in
.vimrc and \`scripts/keyboard/CHEATSHEET.md\` for the full tmux+vim picture.

| Key | Mode | Action |
| --- | ---- | ------ |
| \`<M-h>\` / \`<M-Left>\`  | N/I/V | focus split left (else tmux pane left) |
| \`<M-j>\` / \`<M-Down>\`  | N/I/V | focus split down (else tmux pane down) |
| \`<M-k>\` / \`<M-Up>\`    | N/I/V | focus split up (else tmux pane up) |
| \`<M-l>\` / \`<M-Right>\` | N/I/V | focus split right (else tmux pane right) |
| \`<M-H>\` / \`<M-S-Left>\`  | N/I/V | narrow split (else tmux pane) |
| \`<M-J>\` / \`<M-S-Down>\`  | N/I/V | lengthen split (else tmux pane) |
| \`<M-K>\` / \`<M-S-Up>\`    | N/I/V | shorten split (else tmux pane) |
| \`<M-L>\` / \`<M-S-Right>\` | N/I/V | widen split (else tmux pane) |

